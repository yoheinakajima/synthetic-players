#!/usr/bin/env node
/**
 * Experiment F — 30-round stabilization gate (freeze-packet section E).
 * Computed ONLY from stored Phase 3 trajectories; no LLM calls.
 *
 * Gate (registered by the sign-off response, §7.2): 30 rounds approved iff
 *   - P(stay|win) and P(shift|lose): |rounds1-30 − rounds1-50| ≤ 0.05 each;
 *   - first-order tracker payoff/round: |1-30 − 1-50| ≤ 0.03;
 *   - each conditional has ≥ 30 usable pooled transitions by round 30.
 * Outputs docs/phase4/f-stabilization.md + .json (machine-generated).
 */
import { writeFileSync, mkdirSync } from "node:fs";

const BASE = process.env.API_BASE ?? "http://localhost:80/api";
const api = async (p) => {
  const r = await fetch(BASE + p);
  if (!r.ok) throw new Error(`${p} -> ${r.status}`);
  return r.json();
};

const strategies = await api("/strategies");
const LLM_ID = strategies.find((s) => s.slug === "llm-gpt-4.1").id;
const TRACKER_ID = strategies.find((s) => s.slug === "pattern-tracker").id;

const exps = (await api("/experiments")).filter(
  (e) => e.status === "completed" && e.batchLabel?.startsWith("rock-paper-scissors:llm41")
);
const details = new Map();
for (const e of exps) details.set(e.id, await api(`/experiments/${e.id}`));

function conditionals(upTo) {
  let wN = 0, wS = 0, lN = 0, lS = 0;
  for (const e of exps) {
    const d = details.get(e.id);
    for (const seat of [1, 2]) {
      const sid = seat === 1 ? e.player1StrategyId : e.player2StrategyId;
      if (sid !== LLM_ID) continue;
      const rounds = d.rounds.filter((r) => r.roundNumber <= upTo);
      const acts = rounds.map((r) => (seat === 1 ? r.player1Action : r.player2Action));
      const pays = rounds.map((r) => (seat === 1 ? r.player1Payoff : r.player2Payoff));
      for (let t = 1; t < acts.length; t++) {
        if (pays[t - 1] > 0) { wN++; if (acts[t] === acts[t - 1]) wS++; }
        else if (pays[t - 1] < 0) { lN++; if (acts[t] !== acts[t - 1]) lS++; }
      }
    }
  }
  return { stay: wS / wN, shift: lS / lN, winN: wN, loseN: lN };
}

function trackerPayoff(upTo) {
  const arm = exps.filter((e) => [e.player1StrategyId, e.player2StrategyId].includes(TRACKER_ID));
  const perRun = arm.map((e) => {
    const d = details.get(e.id);
    const seat = e.player1StrategyId === TRACKER_ID ? 1 : 2;
    const rounds = d.rounds.filter((r) => r.roundNumber <= upTo);
    return rounds.reduce((s, r) => s + (seat === 1 ? r.player1Payoff : r.player2Payoff), 0) / rounds.length;
  });
  return { mean: perRun.reduce((a, b) => a + b, 0) / perRun.length, runs: perRun.length };
}

// per-round trajectory of pooled conditionals (for the plot table)
const traj = [];
for (let R = 5; R <= 50; R += 5) {
  const c = conditionals(R);
  traj.push({ upTo: R, stay: c.stay, shift: c.shift, winN: c.winN, loseN: c.loseN, trk: trackerPayoff(R).mean });
}

const c30 = conditionals(30), c50 = conditionals(50);
const t30 = trackerPayoff(30), t50 = trackerPayoff(50);
const dStay = Math.abs(c30.stay - c50.stay);
const dShift = Math.abs(c30.shift - c50.shift);
const dTrk = Math.abs(t30.mean - t50.mean);
const pass = dStay <= 0.05 && dShift <= 0.05 && dTrk <= 0.03 && c30.winN >= 30 && c30.loseN >= 30;

const f = (v, d = 4) => v.toFixed(d);
const json = {
  generatedAt: new Date().toISOString(),
  rounds30: { ...c30, trackerPayoffPerRound: t30.mean },
  rounds50: { ...c50, trackerPayoffPerRound: t50.mean },
  deltas: { stay: dStay, shift: dShift, trackerPayoff: dTrk },
  thresholds: { conditionals: 0.05, trackerPayoff: 0.03, minTransitions: 30 },
  trajectory: traj,
  gatePasses: pass,
  resultingRounds: pass ? 30 : 50,
};
mkdirSync("docs/phase4", { recursive: true });
writeFileSync("docs/phase4/f-stabilization.json", JSON.stringify(json, null, 2));
writeFileSync(
  "docs/phase4/f-stabilization.md",
  `# F Stabilization Packet — 30-round gate (from stored Phase 3 trajectories)

> Machine-generated by \`scripts/phase4-f-stabilization.mjs\`; no new LLM calls. Generated ${json.generatedAt}.

Gate (sign-off §7.2): 30 rounds approved iff each conditional differs ≤ 0.05 between
rounds 1–30 and 1–50, tracker payoff/round differs ≤ 0.03, and each conditional has
≥ 30 usable pooled transitions by round 30.

| Quantity | Rounds 1–30 | Rounds 1–50 | |Δ| | Threshold | OK |
|---|---|---|---|---|---|
| P(stay\\|win), pooled | ${f(c30.stay)} (n=${c30.winN}) | ${f(c50.stay)} (n=${c50.winN}) | ${f(dStay)} | ≤ 0.05 | ${dStay <= 0.05 ? "✔" : "✘"} |
| P(shift\\|lose), pooled | ${f(c30.shift)} (n=${c30.loseN}) | ${f(c50.shift)} (n=${c50.loseN}) | ${f(dShift)} | ≤ 0.05 | ${dShift <= 0.05 ? "✔" : "✘"} |
| First-order tracker payoff/round | ${f(t30.mean)} (${t30.runs} runs) | ${f(t50.mean)} (${t50.runs} runs) | ${f(dTrk)} | ≤ 0.03 | ${dTrk <= 0.03 ? "✔" : "✘"} |
| Pooled win-transitions by r30 | ${c30.winN} | — | — | ≥ 30 | ${c30.winN >= 30 ? "✔" : "✘"} |
| Pooled lose-transitions by r30 | ${c30.loseN} | — | — | ≥ 30 | ${c30.loseN >= 30 ? "✔" : "✘"} |

## Trajectory (pooled, cumulative to round R)

| R | P(stay\\|win) | P(shift\\|lose) | win-N | lose-N | tracker payoff/round |
|---|---|---|---|---|---|
${traj.map((t) => `| ${t.upTo} | ${f(t.stay)} | ${f(t.shift)} | ${t.winN} | ${t.loseN} | ${f(t.trk)} |`).join("\n")}

## Verdict

**Gate ${pass ? "PASSES — F freezes at 30 rounds (switcher at round 16)" : "FAILS — F reverts to 50 rounds (switcher at round 26)"}.**
`
);
console.log(`gate ${pass ? "PASS -> 30 rounds" : "FAIL -> 50 rounds"} | dStay=${f(dStay)} dShift=${f(dShift)} dTrk=${f(dTrk)} winN30=${c30.winN} loseN30=${c30.loseN}`);
